import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import JSZip from 'jszip';

test('editing, history, persistence, presentation and project files', async ({ page }, info) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.slide-row')).toHaveCount(3);
  await page.locator('[data-action="add"]').first().click();
  await expect(page.locator('.slide-row')).toHaveCount(4);
  await page.locator('[data-action="text"]').click();
  await expect(page.locator('#stage [data-element]')).toHaveCount(1);
  await page.getByLabel('Текст объекта', { exact: true }).fill('Проверка редактора');
  await page.getByLabel('Текст объекта', { exact: true }).press('Tab');
  await expect(page.locator('#stage')).toContainText('Проверка редактора');
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('#stage')).toContainText('Ваш текст');
  await page.locator('[data-action="redo"]').click();
  await expect(page.locator('#stage')).toContainText('Проверка редактора');
  await page.getByLabel('Название презентации').fill('Тест Presentation Free');
  await page.getByLabel('Название презентации').press('Tab');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('presentation-free.deck.v1') || '{}').title)).toBe('Тест Presentation Free');
  await page.reload();
  await expect(page.locator('.slide-row')).toHaveCount(4);
  await expect(page.getByLabel('Название презентации')).toHaveValue('Тест Presentation Free');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-action="save-json"]').first().click();
  const download = await downloadPromise; const jsonPath = info.outputPath('roundtrip.json');
  await download.saveAs(jsonPath);
  const saved = JSON.parse(await fs.readFile(jsonPath, 'utf8'));
  expect(saved.slides[1].elements[0].text).toBe('Проверка редактора');
  await page.locator('#open-file').setInputFiles(jsonPath);
  await expect(page.locator('.toast')).toContainText('открыта');
  await page.locator('[data-action="present"]').first().click();
  await expect(page.locator('.presentation-overlay')).toBeVisible();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.presentation-controls')).toContainText('2 / 4');
  await page.keyboard.press('Escape');
  await expect(page.locator('.presentation-overlay')).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('editor.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('PPTX exports editable shapes and imports them back', async ({ page }, info) => {
  await page.goto('/');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-action="export"]').click();
  const download = await downloadPromise; const pptxPath = info.outputPath('roundtrip.pptx');
  await download.saveAs(pptxPath);
  const zip = await JSZip.loadAsync(await fs.readFile(pptxPath));
  expect(zip.file('ppt/presentation.xml')).toBeTruthy();
  const firstSlide = await zip.file('ppt/slides/slide1.xml').async('string');
  expect(firstSlide).toContain('Идеи, которые');
  expect(firstSlide).toContain('<p:sp>');
  await page.locator('#open-file').setInputFiles(pptxPath);
  await expect(page.locator('.toast')).toContainText('открыта');
  await expect(page.locator('.slide-row')).toHaveCount(3);
  await expect(page.locator('#stage')).toContainText('Идеи, которые');
  await expect(page.locator('#stage .text')).toHaveCount(2);
});
