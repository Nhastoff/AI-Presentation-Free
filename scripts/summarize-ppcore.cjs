const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve('research', 'ppcore-complete');
const bundle = JSON.parse(fs.readFileSync(path.join(root, 'evidence-bundle.json'), 'utf8'));
const records = bundle.records;
if (!Array.isArray(records)) throw new Error('Expected complete REA evidence bundle records');
const find = operation => records.find(record => record.operation === operation);
const overview = find('binary_overview');
const procedures = find('list_procedures');
const strings = find('list_strings');
if (!overview || !procedures || !strings) throw new Error('Missing required evidence records');
const rows = procedures.normalized_result;
if (rows.length !== overview.normalized_result.procedure_count) throw new Error('Procedure count mismatch');
if (strings.normalized_result.length !== overview.normalized_result.string_count) throw new Error('String count mismatch');
const summary = {
  target: overview.subject, profile: overview.analysis_profile,
  overview: overview.normalized_result,
  inventories: {
    procedures: rows.length,
    external: rows.filter(row => row.procedure?.external).length,
    thunks: rows.filter(row => row.procedure?.thunk).length,
    internal: rows.filter(row => !row.procedure?.external).length,
    autogenerated_FUN_names: rows.filter(row => /(^|::)FUN_[0-9a-f]+$/i.test(row.value)).length,
    symbol_source_metadata_available: rows.filter(row => row.symbol?.source).length,
    defined_strings: strings.normalized_result.length,
  },
  evidence: records.map(record => ({ id: record.evidence_id, operation: record.operation, confidence: record.confidence, limits: record.limitations })),
};
fs.writeFileSync(path.join(root, 'summary.json'), JSON.stringify(summary, null, 2));
fs.writeFileSync(path.join(root, 'procedures-complete.json'), JSON.stringify({ evidence_id: procedures.evidence_id, subject: procedures.subject, limitations: procedures.limitations, procedures: rows }, null, 2));
fs.writeFileSync(path.join(root, 'strings-complete.json'), JSON.stringify({ evidence_id: strings.evidence_id, subject: strings.subject, limitations: strings.limitations, strings: strings.normalized_result }, null, 2));
for (const record of records.filter(record => record.operation === 'analyze_function')) {
  const data = record.normalized_result;
  const name = data.procedure.name.replace(/[^A-Za-z0-9_-]/g, '_');
  fs.writeFileSync(path.join(root, name + '.pseudocode.c'), `/* Ghidra recovered pseudocode; not original source.\nEvidence: ${record.evidence_id}\n*/\n${data.pseudocode || '/* unavailable */'}`);
  fs.writeFileSync(path.join(root, name + '.assembly.txt'), (data.assembly || []).join('\n'));
}
console.log(JSON.stringify({ counts: summary.inventories, records: records.length }, null, 2));
